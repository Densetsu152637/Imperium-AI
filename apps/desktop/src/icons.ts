/** Other names an icon was saved or catalogued under. */
const ALIASES: Record<string, string> = {
  "book-open": "book",
  zap: "bolt",
  "chart-column": "chart",
  "flask-conical": "flask",
  "gamepad-2": "gamepad",
  home: "house",
};

const ICONS: Record<string, LucideIcon> = Object.fromEntries(ENTRIES.map(([name, icon]) => [name, icon]));
const WORDS: Record<string, string> = Object.fromEntries(ENTRIES.map(([name, , words]) => [name, `${name} ${words}`]));

/** Every icon name, in the order pickers show them. */
export const ICON_NAMES: string[] = ENTRIES.map(([name]) => name);

/** The registered name for `name` (resolving aliases), or null when it is not registered. */
export function iconName(name: string | null | undefined): string | null {
  if (!name) return null;
  if (name in ICONS) return name;
  const alias = ALIASES[name];
  return alias && alias in ICONS ? alias : null;
}

/** The icon for a name or alias, or null when it is not registered. */
export function iconFor(name: string | null | undefined): LucideIcon | null {
  const known = iconName(name);
  return known ? ICONS[known] : null;
}

/** Icon names matching every word of `query` (in the name or its search words). */
export function searchIcons(query: string): string[] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) return ICON_NAMES;
  return ICON_NAMES.filter((name) => words.every((word) => WORDS[name].includes(word)));
}
